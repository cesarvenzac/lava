/**
 * Seeded randomness: the same seed lays out the same lamp, on every screen and on a server. A seed
 * is hashed to 32 bits by cyrb53's mixing, which drives mulberry32. Neither reads the clock or
 * `Math.random`.
 */

/** A seed, text or a number, as 32 bits. */
export function hashOf(seed: string | number): number {
  const text = String(seed);
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 2654435761);
    h2 = Math.imul(h2 ^ c, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  return h1 >>> 0;
}

/** Numbers in [0, 1), the same ones for the same seed. */
export function generator(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
